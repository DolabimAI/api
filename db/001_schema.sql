-- updated_at'i her güncellemede otomatik yazar
create function set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- Log tablolarında güncelleme/silmeyi engeller (belgedeki "güncellenmez ve silinmez" kuralı)
create function forbid_log_change() returns trigger
language plpgsql set search_path = '' as $$
begin
  raise exception '% bir log tablosudur; satırları %', tg_table_name,
    case tg_op when 'UPDATE' then 'güncellenemez' else 'silinemez' end;
end $$;

