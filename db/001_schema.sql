-- Yalnız onaylı parçaları sayar; veri saklamaz.
create view wardrobe_summary with (security_invoker = true) as
select
  w.id                                                         as wardrobe_id,
  count(c.id)::int                                             as total_count,
  count(c.id) filter (where cat.value = 'ust')::int            as top_count,
  count(c.id) filter (where cat.value = 'alt')::int            as bottom_count,
  count(c.id) filter (where cat.value = 'tek_parca')::int      as one_piece_count,
  count(c.id) filter (where cat.value = 'dis')::int            as outer_count,
  count(c.id) filter (where cat.value = 'ayakkabi')::int       as shoes_count,
  count(c.id) filter (where cat.value = 'aksesuar')::int       as accessory_count
from wardrobes w
left join clothes c
  on c.wardrobe_id = w.id
 and c.status_id = (select id from clothing_statuses where value = 'onayli')
left join categories cat on cat.id = c.category_id
group by w.id;

